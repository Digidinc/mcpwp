#!/usr/bin/env bash
#
# Build the Agency distribution zip of MCPWP.
#
# All Pro features are permanently enabled via a build-time marker file,
# includes/agency-license.php (see Mcpwp_License::agency_license_active()) —
# not a wp-config.php constant (issue #863: MCPWP_PRO in wp-config.php is no
# longer honoured by any build). No Freemius SDK, no license key required,
# no wp-config.php changes needed. Includes the self-update channel
# (updates.mcpwp.net).
#
# Intended for: agency clients, white-label deployments, and internal use.
#
# Usage:
#   bash scripts/build-agency.sh
#   bash scripts/build-agency.sh --version 3.2.7

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLUGIN_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
PLUGIN_SLUG="mcpwp"
DIST_NAME="mcpwp-agency"

VERSION=""
while [[ $# -gt 0 ]]; do
	case "$1" in
		--version) VERSION="$2"; shift 2 ;;
		*) echo "Unknown option: $1"; exit 1 ;;
	esac
done

if [[ -z "$VERSION" ]]; then
	VERSION=$(grep -m1 "Version:" "$PLUGIN_DIR/$PLUGIN_SLUG.php" | sed 's/.*Version:[[:space:]]*//' | tr -d '[:space:]')
fi

if [[ -z "$VERSION" ]]; then
	echo "Error: Could not determine version."
	exit 1
fi

echo "==> Building $DIST_NAME v$VERSION (all Pro features unlocked)"

BUILD_DIR=$(mktemp -d)
DEST="$BUILD_DIR/$PLUGIN_SLUG"
trap 'rm -rf "$BUILD_DIR"' EXIT

echo "    Copying plugin files..."
cp -a "$PLUGIN_DIR" "$DEST"

# Remove WP.org banner/icon assets (not needed in plugin zip)
rm -f "$DEST"/assets/banner-*.png
rm -f "$DEST"/assets/icon-*.png
rm -f "$DEST"/assets/screenshot-*.png
rm -f "$DEST"/assets/icon.svg

# No Freemius SDK in agency build — license check bypassed via the marker file below.
rm -rf "$DEST/freemius"
rm -f  "$DEST/includes/freemius-init.php"

echo "    Writing agency license marker (permanent Pro unlock)..."
# This exact string must match Mcpwp_License::AGENCY_MARKER_TOKEN. It is
# deliberately NOT a wp-config.php constant (issue #863) — see the license
# class docblock. Never hand-edit or copy this file between versions; a
# stale token will simply fail closed (agency_license_active() returns
# false), not grant the wrong Pro tier.
AGENCY_MARKER_TOKEN=$(grep -m1 "AGENCY_MARKER_TOKEN" "$PLUGIN_DIR/includes/class-mcpwp-license.php" | sed -E "s/.*=\s*'([^']+)'.*/\1/")
if [[ -z "$AGENCY_MARKER_TOKEN" ]]; then
	echo "Error: Could not read AGENCY_MARKER_TOKEN from class-mcpwp-license.php."
	exit 1
fi
cat > "$DEST/includes/agency-license.php" <<PHP
<?php
// Generated by scripts/build-agency.sh — DO NOT hand-edit or commit this
// file. Its presence with this exact return value is what makes this
// distribution Pro (see Mcpwp_License::agency_license_active()). It ships
// only in the agency ZIP and is never part of the plugin's source tree.
return '$AGENCY_MARKER_TOKEN';
PHP

echo "    Applying .distignore (keeping updater)..."
if [[ -f "$DEST/.distignore" ]]; then
	while IFS= read -r pattern; do
		[[ -z "$pattern" || "$pattern" == \#* ]] && continue
		# Keep the updater so sites auto-update via updates.mcpwp.net
		[[ "$pattern" == *"class-mcpwp-updater.php"* ]] && continue
		pattern="${pattern#/}"
		find "$DEST" -path "$DEST/$pattern" -exec rm -rf {} + 2>/dev/null || true
	done < "$DEST/.distignore"
	rm -f "$DEST/.distignore"
fi

rm -rf "$DEST/scripts"

OUTPUT_DIR="$PLUGIN_DIR/scripts"
OUTPUT_ZIP="$OUTPUT_DIR/$DIST_NAME-$VERSION.zip"

echo "    Creating zip..."
rm -f "$OUTPUT_ZIP"
cd "$BUILD_DIR"
zip -qr "$OUTPUT_ZIP" "$PLUGIN_SLUG/"

echo ""
echo "==> Done: $OUTPUT_ZIP"
echo ""

echo "    Sanity checks:"
ZIP_MANIFEST="$BUILD_DIR/zip-manifest.txt"
unzip -Z1 "$OUTPUT_ZIP" > "$ZIP_MANIFEST"

if grep -q "freemius/" "$ZIP_MANIFEST"; then
	echo "    [FAIL] Freemius SDK found in agency zip"
	exit 1
else
	echo "    [OK] No Freemius SDK"
fi

if grep -q "class-mcpwp-updater.php" "$ZIP_MANIFEST"; then
	echo "    [OK] Updater included (auto-updates via updates.mcpwp.net)"
else
	echo "    [WARN] Updater not found"
fi

if grep -q "includes/agency-license.php" "$ZIP_MANIFEST"; then
	echo "    [OK] Agency license marker present"
else
	echo "    [FAIL] Agency license marker missing — Pro will not unlock"
	exit 1
fi

# Regression guard for issue #863: fail the build if the shipped license
# class ever again honours a wp-config.php constant for Pro.
if grep -Eq "defined\(\s*'MCPWP_PRO'\s*\)" "$DEST/includes/class-mcpwp-license.php"; then
	echo "    [FAIL] class-mcpwp-license.php still honours a wp-config.php MCPWP_PRO constant"
	exit 1
else
	echo "    [OK] No wp-config.php MCPWP_PRO override in license class"
fi

# #943 S1 review round 3, N4: no Freemius SDK in this build either (removed
# above) — uninstall.php is the only mechanism that will ever drop the graph
# tables here, same reasoning as build-selfhosted.sh's check.
if grep -q "^$PLUGIN_SLUG/uninstall.php$" "$ZIP_MANIFEST"; then
	echo "    [OK] uninstall.php present (this build has no Freemius to own uninstall instead)"
else
	echo "    [FAIL] uninstall.php missing — nothing will drop the graph tables on uninstall"
	exit 1
fi

FILE_COUNT=$(unzip -l "$OUTPUT_ZIP" | tail -1 | awk '{print $2}')
echo "    [INFO] $FILE_COUNT files in zip"
echo ""
echo "All Pro features permanently enabled via the agency license marker file. No license key or wp-config.php changes needed."
